// テスティモニアルデータ定義
// 新しい声を追加するには、testimonials 配列にオブジェクトを追加するだけでOK
// 注意: プレースホルダーは必ず実際の声に差し替えてからリリースすること

export interface Testimonial {
  /** 引用文（2-3文）。お客様が実際に話した内容をそのまま掲載する */
  quote: string;
  /** 氏名またはハンドルネーム（許諾範囲に合わせてイニシャル・匿名も可） */
  name: string;
  /** 肩書き・属性（例: 児童発達支援事業所 管理者） */
  role: string;
  /** 会社・団体名（掲載許諾がある場合のみ） */
  company?: string;
  /** アバター画像パス（/public 配下の相対パス） */
  avatar?: string;
  /** 出典区分 */
  source: "community" | "client";
}

